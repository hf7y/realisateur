#!/usr/bin/env bash
# branch-protection-provision.sh -- give every ecosystem repo a protected
# default branch with at least one REQUIRED CHECK, so that the one sanctioned
# merge command cannot silently self-merge an unreviewed PR.
#
# RUNNER: bin/tests/branch-protection-provision.test.sh
# GUARD-TEST: bin/tests/branch-protection-provision.test.sh
# GATE: strict
#
# TRAPS (the rest of this header is in the vault):
# bin/repo-settings-provision.sh declined this job because it would have to
# name check contexts, and `suites`/`markdown-cost` are realisateur's own job
# names -- forcing them estate-wide wedges every repo named differently. That
# objection is this script's design: it never names a context. It reads each
# repo's own check runs from the head of its most recent PR -- evidence a check
# RUNS ON PULL REQUESTS -- and requires those. (Parsing `on:` out of workflow
# YAML asserts what a file claims, not what GitHub ran.)
# A repo with no CI is reported NOCI and left alone, never silently skipped:
# requiring a context no workflow produces wedges every PR, which is worse than
# the bug. That list is hf7y/realisateur#285's worklist, measured.
#

set -uo pipefail

CLI_NAME='branch-protection-provision.sh'
CLI_SUMMARY='protect every rostered repo behind its OWN required check, so --auto cannot self-merge'
CLI_USAGE='  branch-protection-provision.sh              report, change nothing
  branch-protection-provision.sh <repo>...    report for named repo(s)
  branch-protection-provision.sh --apply [<repo>...]   protect what it can
  branch-protection-provision.sh --strict [<repo>...]  exit 1 if unprotected'
CLI_FLAGS='--apply --strict'
CLI_EXITS='  0  read every rostered repo; no --strict given, or --strict given and
     every repo is protected
  1  --strict was given and at least one repo is unprotected (checked after
     --apply, if both are given, so --apply --strict verifies its own work)
  2  BLIND -- at least one repo could not be read at all, or the roster
     matched nothing. NEVER 0: could-not-look is not clean, and it is not
     gated behind --strict, because a run that saw nothing has established
     nothing whether or not the caller asked it to gate.'
CLI_POSITIONAL=any
. "$(dirname "${BASH_SOURCE[0]}")/lib/cli-guard.sh"
cli_guard "$@"

OWNER="${BPP_OWNER:-hf7y}"
GH_BIN="${GH_BIN:-gh}"

# THE ROSTER. Kept identical to bin/decision-rot.sh's, and for the same reason
# stated there: the fifteen projects dispatch actually reads, plus the three
# ecosystem repos that carry decisions but are never dispatched. Re-derive, do
# not trust:  gh api repos/hf7y/scheduler/contents/schedule -q '.[].name'
ROSTER=(
  baudin bibliothecaire chezz crt ecosim gardien groc-mangr nine-speakers
  realisateur scheduler secretaire senechal sequestria vim-arcade wtul
  verbs front-door basheur
)

APPLY=0
STRICT=0
want=()
for a in "$@"; do
  case "$a" in
    --apply)  APPLY=1 ;;
    --strict) STRICT=1 ;;
    *)        want+=("$a") ;;
  esac
done

names=()
for p in "${ROSTER[@]}"; do
  if [ "${#want[@]}" -gt 0 ]; then
    skip=1; for w in "${want[@]}"; do [ "$w" = "$p" ] && skip=0; done
    [ "$skip" -eq 1 ] && continue
  fi
  names+=("$p")
done
cli_require_matched want names

command -v "$GH_BIN" >/dev/null || { echo "$CLI_NAME: $GH_BIN not on PATH" >&2; exit 2; }

echo "branch-protection-provision -- $(date '+%Y-%m-%d %H:%M')"
if [ "$APPLY" = 1 ]; then
  echo "(--apply: protecting every repo below that has a discoverable check)"
else
  echo "(read-only: reporting, changing nothing -- pass --apply to protect)"
fi
echo

blind=0
unprotected=0
noci=0
protected=0

# Contexts a required check must never be built from. pages-build-deployment
# is generated by GitHub for Pages repos and never reports on a pull request,
# so requiring it wedges every PR -- the exact failure this script exists to
# avoid, arriving through the back door.
# Read the required contexts, or print NOTHING if the branch is unprotected.
#
# THE TRAP, hit live by this script's own first run: an unprotected branch
# 404s, and `gh api` prints the 404's JSON BODY to stdout while --jq finds no
# match. Capturing stdout alone therefore yields the string
# `{"message":"Branch not protected",...}` -- non-empty, so a naive `[ -n ]`
# test reads "unprotected" as "protected" and the run reported 18 of 18
# protected when 16 had no protection at all. Exactly the silent-zero this
# estate keeps paying for, produced by the guard written to end it. So: gate
# on gh's EXIT STATUS first, and never look at the body unless it succeeded.
read_contexts() {
  local out
  out="$(api_get "repos/$1/branches/$2/protection")" || return 0
  printf '%s' "$out" | jq -r '[.required_status_checks.contexts[]?] | join(",")' 2>/dev/null
}

# The same trap, and it bit TWICE: every read below has to gate on the exit
# status, or the error body becomes the answer. Second instance was the
# default_branch read -- an inaccessible repo came back with the 404 body as
# its "branch name" and was reported NOCI (a fact about its CI) instead of
# BLIND (could not look at all).
api_get() { "$GH_BIN" api "$1" 2>/dev/null; }

context_is_usable() {
  case "$1" in
    pages-build-deployment|'') return 1 ;;
    *) return 0 ;;
  esac
}

for name in "${names[@]}"; do
  slug="$OWNER/$name"

  if repo_json="$(api_get "repos/$slug")"; then
    branch="$(printf '%s' "$repo_json" | jq -r '.default_branch // empty' 2>/dev/null)"
  else
    branch=''
  fi
  if [ -z "$branch" ]; then
    echo "  BLIND $name: could not read the repo (no access, or it does not exist)"
    blind=$((blind+1))
    continue
  fi

  # What is protected TODAY. A repo can be protected with zero required
  # contexts -- that still leaves --auto with nothing to queue behind, so it
  # is counted as unprotected for this guard's purpose, not as ok.
  have="$(read_contexts "$slug" "$branch")"

  if [ -n "$have" ]; then
    echo "  ok    $name ($branch): required [$have]"
    protected=$((protected+1))
    continue
  fi

  # Discover this repo's OWN contexts from the head commit of its most recent
  # pull request -- evidence a check runs on PRs, not a claim from YAML.
  if pr_json="$(api_get "repos/$slug/pulls?state=all&per_page=1&sort=updated&direction=desc")"; then
    pr_sha="$(printf '%s' "$pr_json" | jq -r '.[0].head.sha // empty' 2>/dev/null)"
  else
    pr_sha=''
  fi

  found=()
  if [ -n "$pr_sha" ] && cr_json="$(api_get "repos/$slug/commits/$pr_sha/check-runs")"; then
    while IFS= read -r c; do
      context_is_usable "$c" || continue
      dup=0; for f in ${found[@]+"${found[@]}"}; do [ "$f" = "$c" ] && dup=1; done
      [ "$dup" -eq 0 ] && found+=("$c")
    done < <(printf '%s' "$cr_json" | jq -r '.check_runs[]?.name' 2>/dev/null)
  fi

  # Drop MATRIX LEGS if any non-matrix context survives. A matrix job reports
  # one context per leg, named `job (1/3)`, and the leg count is part of the
  # name -- so requiring `playwright (3/3)` (live on hf7y/chezz) wedges every
  # PR the day the matrix is resized to 4, with a required check that can
  # never report again. The stable sibling jobs are the safe thing to require.
  # If a repo has ONLY matrix legs, they are kept: a brittle required check
  # still beats silent self-merging, and it fails loudly rather than quietly.
  stable=()
  for f in ${found[@]+"${found[@]}"}; do
    case "$f" in *' ('*')') ;; *) stable+=("$f") ;; esac
  done
  if [ "${#stable[@]}" -gt 0 ] && [ "${#stable[@]}" -ne "${#found[@]}" ]; then
    echo "        (dropping $(( ${#found[@]} - ${#stable[@]} )) matrix leg(s): a resized matrix would wedge every PR)"
    found=("${stable[@]}")
  fi

  if [ "${#found[@]}" -eq 0 ]; then
    if [ -z "$pr_sha" ]; then
      why="no pull request has ever been opened, so no check has ever reported on one"
    else
      why="no check ran on the head of its most recent PR ($pr_sha)"
    fi
    echo "  NOCI  $name ($branch): $why"
    echo "        -> cannot be protected honestly; requiring an absent context wedges every PR. This is the #285 CI-rollout worklist."
    noci=$((noci+1))
    unprotected=$((unprotected+1))
    continue
  fi

  ctx_list="$(IFS=,; echo "${found[*]}")"
  echo "  UNPROT $name ($branch): no required check; its own PR checks are [$ctx_list]"

  [ "$APPLY" = 1 ] || { unprotected=$((unprotected+1)); continue; }

  # jq builds the payload: contexts is an array of strings and hand-rolling
  # that in a shell string is how a repo gets a required check literally named
  # `"tests"` with the quotes in it.
  payload="$(printf '%s\n' "${found[@]}" | jq -R . | jq -sc \
    '{required_status_checks: {strict: false, contexts: .},
      enforce_admins: false,
      required_pull_request_reviews: null,
      restrictions: null,
      allow_force_pushes: false,
      allow_deletions: false}')"

  if printf '%s' "$payload" \
      | "$GH_BIN" api -X PUT "repos/$slug/branches/$branch/protection" --input - >/dev/null 2>&1; then
    # Verify by RE-READING, not by trusting the write's exit status.
    now="$(read_contexts "$slug" "$branch")"
    if [ -n "$now" ]; then
      echo "        -> protected, required [$now]"
      protected=$((protected+1))
    else
      echo "        -> WROTE but re-read shows no required check -- treat as unprotected"
      unprotected=$((unprotected+1))
    fi
  else
    echo "        -> FAILED to write protection (needs admin on $slug)"
    unprotected=$((unprotected+1))
  fi
done

echo
echo "== $protected protected, $unprotected unprotected ($noci of them with no CI at all), $blind BLIND, out of ${#names[@]} repo(s) =="

if [ "$blind" -gt 0 ]; then
  echo "$CLI_NAME: $blind repo(s) unreadable -- the counts above are NOT trustworthy."
  exit 2
fi
if [ "$STRICT" = 1 ] && [ "$unprotected" -gt 0 ]; then
  exit 1
fi
exit 0
