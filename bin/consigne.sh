#!/usr/bin/env bash
# consigne.sh -- the vault-consign step of PROSE-REAPING.md, mechanized.
#
# PROSE-REAPING.md names three destinations for a paragraph whose premise no
# longer needs live enforcement: stays in the repo, becomes a GitHub issue, or
# goes to the Obsidian vault (~/ecosystem1/ecosystem1/<project>/) as narrative.
# The first two both have tooling (a plain edit; `consulte`/`gh issue
# create`-shaped flows). The third has never had any -- every vault commit to
# date (`git -C ~/ecosystem1/ecosystem1 log --grep '^consign:'`) was done by
# hand: copy files, write a commit message in the established convention,
# commit locally, and -- the step most likely to be forgotten under hand
# execution -- never push. This script is that step, made repeatable.
#
# WHY NEVER PUSH IS IN THE SCRIPT, NOT JUST THE DOCS. Zach's 2026-08-06 note:
# "Prose should not be going to github, especially to avoid issues with
# licensing while we implement proper ethics guards around IP." A tool that
# could push and simply isn't told to is one flag away from violating that.
# This tool carries no push code path at all -- not "push disabled by
# default", but no `git push` anywhere in the file. See RECORD.
#
# WHAT IT DOES NOT DECIDE. PROSE-REAPING.md's criterion ("does this paragraph
# describe a premise that still holds?") is a per-paragraph judgement call --
# this script does not read prose or apply that criterion. It is the
# mechanical back half: once a human or an agent has decided WHAT is narrative
# and drafted the vault file(s), this commits them correctly. Drafting the
# commit message in the vault's established tone (see EXAMPLES) is still the
# caller's job; -m/--message is required, not generated.
#
# Modelled on the VERB_NAME / lib/verb.sh shape used by realisateur's other
# verbs (arpente, juge, epluche) so this can ship through the same
# hf7y/verbs build once it graduates out of draft -- see the PR body for what
# is still missing before that (subcommand split, man page, DEPENDS.tsv rows,
# a bashified branch). This file is deliberately a single plain script for
# now: it has one job and no subcommands yet.
set -uo pipefail

SELF="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"

VAULT_ROOT="${CONSIGNE_VAULT_ROOT:-$HOME/ecosystem1/ecosystem1}"

die() { printf 'consigne: %s\n' "$*" >&2; exit 2; }

usage() {
  cat <<'EOF'
consigne -- consign files out of a project repo into the Obsidian vault
            (the vault-consign step of PROSE-REAPING.md), committed
            locally and NEVER pushed.

usage:
  consigne --from <project> --file <path> [--file <path> ...] -m <message-file> [--apply]
  consigne --from <project> --diff <treeish> -m <message-file> [--apply]

  --from <project>   project name; source defaults to
                      $HOME/Documents/Projects/<project> (override with
                      CONSIGNE_SOURCE_ROOT)
  --file <path>       a file (repo-relative or absolute, under the source
                       repo) to copy into the vault. Repeatable.
  --diff <treeish>    instead of --file, take every path `git diff --name-only
                       <treeish>` reports in the source repo (still filtered
                       to files that exist at HEAD -- deleted paths are
                       skipped, not consigned as empty files)
  -m, --message <file> path to a prepared commit message, in the vault's
                       "consign: <summary>" convention. See EXAMPLES below.
                       Required. Not generated by this tool -- drafting the
                       narrative is the judgement call PROSE-REAPING.md asks
                       a human or an agent to make, not this script.
  --dest-name <name>  filename to write under the vault's
                       <project>/ directory when copying a single --file
                       whose own name should not carry over verbatim
                       (e.g. reaping ESTATE.md into
                       ESTATE-findings-and-history-<date>.md). Only valid
                       with exactly one --file.
  --apply             actually copy + commit. Without it: dry run, prints
                       what would be written and the commit message,
                       changes nothing.
  -n, --dry-run       same as omitting --apply (explicit form)
  -h, --help          this text

EXIT STATUS
  0  committed (--apply) or dry run completed cleanly
  2  usage error
  4  GAP -- vault repo missing, source repo missing, or check-project-busy
     reports BUSY on the source project
  5  BROKEN -- git add/commit failed after files were copied

NEVER PUSHES. There is no code path in this script that runs `git push`
against the vault remote. See PROSE-REAPING.md and the header comment.

EXAMPLES
  Recent vault commits, for the message convention this expects in -m:
    git -C ~/ecosystem1/ecosystem1 log --grep '^consign:' --format='%H %s'
EOF
}

from=""; files=(); diff_ref=""; msgfile=""; dest_name=""; apply=0

while [ $# -gt 0 ]; do
  case "$1" in
    --from) from="${2:?--from needs a project name}"; shift 2 ;;
    --file) files+=("${2:?--file needs a path}"); shift 2 ;;
    --diff) diff_ref="${2:?--diff needs a treeish}"; shift 2 ;;
    -m|--message) msgfile="${2:?--message needs a file path}"; shift 2 ;;
    --dest-name) dest_name="${2:?--dest-name needs a filename}"; shift 2 ;;
    --apply) apply=1; shift ;;
    -n|--dry-run) apply=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1 (try --help)" ;;
  esac
done

[ -n "$from" ] || die "--from <project> is required"
[ -n "$msgfile" ] || die "-m/--message <file> is required"
[ -f "$msgfile" ] || die "message file not found: $msgfile"
[ "${#files[@]}" -gt 0 ] || [ -n "$diff_ref" ] || die "give --file (repeatable) or --diff <treeish>"
[ "${#files[@]}" -eq 0 ] || [ -z "$diff_ref" ] || die "--file and --diff are mutually exclusive"
[ -n "$dest_name" ] && [ "${#files[@]}" -ne 1 ] && die "--dest-name only valid with exactly one --file"

source_root="${CONSIGNE_SOURCE_ROOT:-$HOME/Documents/Projects}/$from"
[ -d "$source_root/.git" ] || {
  printf 'consigne: GAP: no git repo at %s\n' "$source_root" >&2
  exit 4
}

if [ -x "$SELF/bin/check-project-busy.sh" ]; then
  busy="$("$SELF/bin/check-project-busy.sh" "$from" 2>&1)"
  case "$busy" in
    BUSY*)
      printf 'consigne: GAP: %s is busy, refusing to read it mid-run -- %s\n' "$from" "$busy" >&2
      exit 4 ;;
  esac
fi

[ -d "$VAULT_ROOT/.git" ] || {
  printf 'consigne: GAP: no vault repo at %s\n' "$VAULT_ROOT" >&2
  exit 4
}

if [ -n "$diff_ref" ]; then
  while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    [ -f "$source_root/$rel" ] || continue   # deleted at HEAD: not consigned
    files+=("$rel")
  done < <(git -C "$source_root" diff --name-only "$diff_ref" -- 2>/dev/null)
  [ "${#files[@]}" -gt 0 ] || die "no surviving files in \`git diff --name-only $diff_ref\` under $source_root"
fi

dest_dir="$VAULT_ROOT/$from"

echo "consigne -- $from -> ${dest_dir#$HOME/}"
[ "$apply" -eq 1 ] && echo "mode: APPLY (copies + commits locally; never pushes)" \
                    || echo "mode: DRY RUN (writes nothing -- pass --apply to act)"
echo

plan=()
for f in "${files[@]}"; do
  rel="${f#"$source_root"/}"
  src="$source_root/$rel"
  [ -f "$src" ] || { printf 'consigne: not a file, skipping: %s\n' "$f" >&2; continue; }
  if [ -n "$dest_name" ]; then
    dst="$dest_dir/$dest_name"
  else
    dst="$dest_dir/$(basename "$rel")"
  fi
  plan+=("$src:$dst")
  printf '  %s\n      -> %s\n' "$rel" "${dst#$VAULT_ROOT/}"
done
[ "${#plan[@]}" -gt 0 ] || die "nothing to consign after filtering"

echo
echo "commit message:"
sed 's/^/  | /' "$msgfile"

[ "$apply" -eq 1 ] || { echo; echo "dry run: no files copied, nothing committed."; exit 0; }

mkdir -p "$dest_dir" || { printf 'consigne: BROKEN: could not create %s\n' "$dest_dir" >&2; exit 5; }

copied=()
for pair in "${plan[@]}"; do
  src="${pair%%:*}"; dst="${pair#*:}"
  cp -- "$src" "$dst" || { printf 'consigne: BROKEN: copy failed: %s -> %s\n' "$src" "$dst" >&2; exit 5; }
  copied+=("$dst")
done

git -C "$VAULT_ROOT" add -- "${copied[@]}" || {
  printf 'consigne: BROKEN: git add failed in %s\n' "$VAULT_ROOT" >&2; exit 5
}
if ! git -C "$VAULT_ROOT" commit -q -F "$msgfile"; then
  printf 'consigne: BROKEN: git commit failed in %s (nothing was pushed either way)\n' "$VAULT_ROOT" >&2
  exit 5
fi
sha="$(git -C "$VAULT_ROOT" rev-parse --short HEAD)"
ahead="$(git -C "$VAULT_ROOT" rev-list --count '@{u}..HEAD' 2>/dev/null || echo '?')"
printf 'consigne: committed %s locally to %s (%s ahead of upstream, NOT pushed)\n' "$sha" "$VAULT_ROOT" "$ahead"
