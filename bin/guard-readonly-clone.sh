#!/usr/bin/env bash
# guard-readonly-clone.sh -- refuse a local commit into a self-dev account's
# clone of a repo that is not its own project.
#
# WHY. wire-selfdev-git.sh gives an account read-write credentials for
# exactly one repo, its own project, and read-only for the rest (scheduler,
# realisateur, senechal -- see setup-selfdev-project.sh: "READ-WRITE only for
# the account's own repo; read-only for the three shared"). Read-only
# credentials stop a PUSH. Nothing stopped a local COMMIT. wtul's scheduler
# dispatch clone at ~/Documents/Projects/scheduler took a local commit
# anyway, diverged from origin, and sat PULL FROZEN for 3 ticks dispatching
# stale code before a human reset it by hand (hf7y/scheduler#321).
#
# THE CHECK IS PATH-BASED, evaluated live at commit time -- not a per-clone
# install that a clone made after some pass ran would be missing (the exact
# failure stamp-verb-build.sh's own header argues against for the sibling
# Verb-Build hook, and the same argument holds here more strongly: once this
# is wired for an account, ANY clone that later appears directly under
# $PROJECTS is covered without re-running anything).
#
# WHAT THIS DOES NOT TOUCH. A clone anywhere other than directly under
# $PROJECTS -- a /tmp scratch clone, a worktree, a clone under a different
# root -- is exactly where CLAUDE.md's cross-repo draft-PR workflow (rule 6:
# "clone it, make the change, open a DRAFT pull request there") is expected
# to commit. This guard inspects the path at commit time and only refuses
# inside $PROJECTS/<name> where <name> != this account's own name; sanctioned
# work anywhere else is untouched.
#
# THE SAME HOOK_DIR AS stamp-verb-build.sh, deliberately: one shared
# core.hooksPath slot per account, two independently-generated files in it
# (prepare-commit-msg, pre-commit). Neither script needs the other to have
# run first -- whichever runs first claims the slot, the other recognizes it
# as already-owned and just adds its file.

set -uo pipefail

CLI_NAME='guard-readonly-clone.sh'
CLI_SUMMARY="refuse a local commit into a self-dev account's read-only infrastructure clones"
CLI_USAGE='  guard-readonly-clone.sh              --check (default): is this account guarded?
  guard-readonly-clone.sh --apply      install the commit hook for THIS account
  guard-readonly-clone.sh --retire     remove it (with --apply; --check alone prints what would go)'
CLI_FLAGS='--check --apply --retire'
CLI_POSITIONAL=none
CLI_EXITS='  0  this account is guarded, witnessed by running the hook
  1  findings: not wired, wired but unverified, or hooksPath owned elsewhere
  2  usage error'
. "$(dirname "${BASH_SOURCE[0]}")/lib/cli-guard.sh"
cli_guard "$@"

# --- knobs, so the suite can run against a fixture home with no real git
# config and no real $PROJECTS tree.
HOOK_DIR="${STAMP_HOOK_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/verb-stamp/hooks}"
HOOK="$HOOK_DIR/pre-commit"
PROJECTS="${INSTALLE_PROJECTS:-$HOME/Documents/Projects}"

MODE=check; RETIRE=0
for a in "$@"; do
  case "$a" in
    --check)  MODE=check ;;
    --apply)  MODE=apply ;;
    --retire) RETIRE=1 ;;
  esac
done

PASS=0; GAPS=0; BAD=0
ok()  { printf '  ok    %s\n' "$*"; PASS=$((PASS+1)); }
gap() { printf '  gap   %s\n' "$*"; GAPS=$((GAPS+1)); }
bad() { printf '  bad   %s\n' "$*"; BAD=$((BAD+1)); }
act() { printf '  ..    %s\n' "$*"; }

# Generated rather than shipped as a file of its own, same reasoning as
# stamp-verb-build.sh's write_hook(): a second file in the bootstrap set is
# another copy that rots. $PROJECTS is baked in at install time so the hook
# holds no logic of its own for finding it.
write_hook() {
  mkdir -p "$HOOK_DIR" || return 1
  cat > "$HOOK" <<EOF
#!/bin/sh
# GENERATED by realisateur bin/guard-readonly-clone.sh -- do not edit here.
# Refuses a commit into a clone directly under $PROJECTS that is not this
# account's own project (hf7y/scheduler#321). A clone anywhere else is
# untouched -- see this script's header for why that boundary matters.
top="\$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0
case "\$top" in
  "$PROJECTS"/*) ;;
  *) exit 0 ;;
esac
rel="\${top#"$PROJECTS"/}"
name="\${rel%%/*}"
[ "\$name" = "\$(id -un)" ] && exit 0
echo "REFUSED: \$top is read-only infrastructure, not \$(id -un)'s own project -- commit through a pull request against origin instead (hf7y/scheduler#321)" >&2
exit 1
EOF
  chmod 755 "$HOOK"
}

echo "== guard-readonly-clone ($MODE) -- $(id -un)@$(hostname -s 2>/dev/null || echo '?') =="
echo

# --- who owns core.hooksPath, same three-way read as stamp-verb-build.sh ---
cur="$(git config --global core.hooksPath 2>/dev/null)"; cfg_rc=$?
if [ "$cfg_rc" -gt 1 ]; then
  bad "cannot read this account's global git config (git config exited $cfg_rc). Nothing was changed -- an unreadable config is not an empty one."
  echo; printf '%d ok, %d gap, %d bad\n' "$PASS" "$GAPS" "$BAD"
  exit 1
fi

if [ "$RETIRE" = 1 ]; then
  if [ ! -e "$HOOK" ]; then
    ok "nothing to retire: no $HOOK"
  elif [ "$MODE" != apply ]; then
    act "would remove $HOOK"
    act "not removed (--check). Re-run with --apply."
  else
    rm -f "$HOOK"
    # core.hooksPath itself is left alone -- prepare-commit-msg (or some
    # future sibling) may still need it; only this script's own file goes.
    [ -e "$HOOK" ] && bad "removed $HOOK but it is STILL present" || ok "guard retired: $HOOK removed"
  fi
  echo; printf '%d ok, %d gap, %d bad\n' "$PASS" "$GAPS" "$BAD"
  [ "$BAD" -eq 0 ] || exit 1
  exit 0
fi

case "$cur" in
  "$HOOK_DIR") ;;
  '') if [ "$MODE" != apply ]; then
        gap "core.hooksPath is unset -- this account is not guarded"
        act "would write $HOOK and point core.hooksPath at $HOOK_DIR"
        act "not installed (--check). Re-run with --apply."
        echo; printf '%d ok, %d gap, %d bad\n' "$PASS" "$GAPS" "$BAD"
        exit 1
      fi ;;
  *)  # Someone else's hooks directory -- taking it over would silently
      # disable whatever else it holds. Same refusal stamp-verb-build.sh
      # makes; the two scripts agree on what "owned" means because they
      # compute the identical HOOK_DIR default.
      bad "core.hooksPath is already $cur, which this command does not own. Reconcile deliberately; nothing was changed."
      echo; printf '%d ok, %d gap, %d bad\n' "$PASS" "$GAPS" "$BAD"
      exit 1 ;;
esac

if [ "$MODE" = apply ]; then
  write_hook || { bad "could not write $HOOK"; echo; exit 1; }
  git config --global core.hooksPath "$HOOK_DIR"
fi

# --- WITNESS: run the hook, not just check it exists. Only the "outside
# $PROJECTS" case is safe to probe against a REAL host here -- proving the
# refusal case needs a fixture directly under $PROJECTS, and creating one on
# a live host for a witness would be exactly the kind of stray clutter this
# script exists to prevent. That case is covered by
# bin/tests/guard-readonly-clone.test.sh instead, with $PROJECTS itself
# sandboxed.
if [ -x "$HOOK" ] && [ "$(git config --global core.hooksPath 2>/dev/null || true)" = "$HOOK_DIR" ]; then
  W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
  git init -q "$W/scratch-clone"
  git -C "$W/scratch-clone" config user.email test@example.com
  git -C "$W/scratch-clone" config user.name test
  if ( cd "$W/scratch-clone" && "$HOOK" ) >/dev/null 2>&1; then
    ok "the hook does not touch a clone outside \$PROJECTS (cross-repo draft-PR work stays possible)"
  else
    bad "the hook refused inside a clone OUTSIDE \$PROJECTS -- it would block sanctioned cross-repo work"
  fi
else
  gap "not wired: core.hooksPath is ${cur:-unset} and $HOOK is $([ -x "$HOOK" ] && echo present || echo absent)"
fi

echo
printf '%d ok, %d gap, %d bad\n' "$PASS" "$GAPS" "$BAD"
[ "$GAPS" -eq 0 ] && [ "$BAD" -eq 0 ] || exit 1
exit 0
